// Run with node tests/browser.mjs against python3 -m simulator.server.
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require('playwright');
const {mkdir}=await import('node:fs/promises');
await mkdir('output/playwright',{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
page.setDefaultTimeout(6000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const assert=(value,message)=>{if(!value)throw new Error(message)};
await page.goto('http://127.0.0.1:8080');
await page.waitForFunction(()=>document.querySelector('#scenario')&&!document.querySelector('#simulation').hidden);
// Reset simulator state so this test can be rerun on an existing server.
await page.request.post('http://127.0.0.1:8080/api/scenario',{headers:{'X-Operator-Token':'demo-token'},data:{scenario:'normal'}});
await page.waitForTimeout(5000);
await page.getByLabel('Operator token').fill('demo-token');
await page.getByRole('button',{name:'Connect controls',exact:true}).click();
await page.getByRole('button',{name:'Reset stop',exact:true}).click();
await page.waitForTimeout(250);
await page.getByRole('button',{name:'Arm rover',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('#arm').disabled);
await page.getByRole('button',{name:'Start inspection',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('#phase').textContent==='Inspect');
await page.getByLabel('Simulation scenario').selectOption('gas');
await page.waitForFunction(()=>document.querySelector('#phase').textContent==='Ventilate');
assert((await page.locator('#fan').innerText())==='Running','fan must run on gas hazard');
await page.getByRole('button',{name:'Emergency stop',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('#phase').textContent==='Emergency stop');
await page.getByLabel('Simulation scenario').selectOption('normal');
await page.waitForTimeout(5000);
await page.getByRole('button',{name:'Reset stop',exact:true}).click();
await page.waitForTimeout(500);
await page.getByRole('button',{name:'Arm rover',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('#arm').disabled && document.querySelector('#phase').textContent==='Manual');
const forward=page.getByRole('button',{name:'Drive forward',exact:true});
await forward.hover();await page.mouse.down();
await page.waitForFunction(()=>Number(document.querySelector('#throttle').dataset.value)>0,{},{timeout:1200});
assert(Number(await page.locator('#throttle').getAttribute('data-value'))>0,'manual hold must drive');
await page.mouse.up();await page.waitForFunction(()=>Number(document.querySelector('#throttle').getAttribute('data-value'))===0,{},{timeout:1500});
assert(Number(await page.locator('#throttle').getAttribute('data-value'))===0,'release must stop');
await page.evaluate(()=>scrollTo(0,0));
await page.screenshot({path:'output/playwright/desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});await page.evaluate(()=>scrollTo(0,0));await page.screenshot({path:'output/playwright/mobile.png',fullPage:true});
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile horizontal overflow');
assert(errors.length===0,'browser errors: '+errors.join(','));
await browser.close();console.log('PASS: autonomous hazard, fan, emergency stop, manual hold/release, desktop/mobile, no browser errors');
